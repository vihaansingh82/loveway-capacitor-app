  function norm(t) { return (t || '').replace(/\s+/g, ' ').trim(); }

  /* text wale leaf elements: script/style/select chhod kar */
  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, SELECT: 1, OPTION: 1, IMG: 1, SVG: 1, BR: 1, HR: 1 };

  function collect() {
    var out = [];
    var all = document.querySelectorAll('body *');
    for (var i = 0; i < all.length; i++) {
      var el = all[i];
      if (SKIP[el.tagName]) continue;
      if (el.closest('script,style,select')) continue;
      if (el.children.length !== 0) continue;      // sirf leaf
      out.push(el);
    }
    return out;
  }

  function applySite() {
    var f = field(window.LW_CURRENT);

    collect().forEach(function (el) {
      /* pehli baar: original text yaad kar lo */
      if (!el.hasAttribute('data-lw-src')) {
        var t = norm(el.textContent);
        if (!t) return;
        el.setAttribute('data-lw-src', t);
      }
      var key = el.getAttribute('data-lw-src');
      var row = T[key];
      if (row && row[f]) el.textContent = row[f];
    });

    /* placeholders */
    document.querySelectorAll('input[placeholder],textarea[placeholder]').forEach(function (el) {
      if (!el.hasAttribute('data-lw-ph')) {
        var p = norm(el.getAttribute('placeholder'));
        if (!p) return;
        el.setAttribute('data-lw-ph', p);
      }
      var row = T[el.getAttribute('data-lw-ph')];
      if (row && row[f]) el.setAttribute('placeholder', row[f]);
    });

    /* page title */
    if (!document.documentElement.hasAttribute('data-lw-title')) {
      document.documentElement.setAttribute('data-lw-title', norm(document.title));
    }
    var trow = T[document.documentElement.getAttribute('data-lw-title')];
    if (trow && trow[f]) document.title = trow[f];

    document.documentElement.lang =
      (f === 'br' || f === 'hyd') ? 'hi' : f;

    /* select ko current bhaasha par set rakho */
    document.querySelectorAll('select.lw-lang-select, #siteLanguage, #languageSelect')
      .forEach(function (s) {
        var want = canonical(window.LW_CURRENT);
        if (s.querySelector('option[value="' + want + '"]')) s.value = want;
      });
  }

